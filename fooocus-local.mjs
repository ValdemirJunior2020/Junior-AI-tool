import "dotenv/config";
import { chromium } from "playwright-core";
import { mkdir, readdir, stat, copyFile, unlink } from "node:fs/promises";
import path from "node:path";
import { DATA, STORE } from "./db.mjs";

// Official Fooocus is a Gradio UI, NOT the unrelated Fooocus-API REST service.
// This local-only bridge drives that UI via Chrome and picks up its saved output.
// Tested on source-level selectors; needs end-to-end validation on the target PC.
export const OUTPUT_DIR = path.join(DATA, "fooocus-output");
export const TEMP_DIR = path.join(DATA, "fooocus-temp");
const imageExtensions = new Set([".png", ".jpg", ".jpeg", ".webp"]);
const removableExtensions = new Set([".png", ".jpg", ".jpeg", ".webp", ".html", ".json"]);
const localUrl = () => process.env.FOOOCUS_UI_URL || "http://127.0.0.1:7865";
export function assertLocalFooocusUrl() {
  const url = new URL(localUrl());
  if (url.protocol !== "http:" || !["127.0.0.1", "localhost", "[::1]"].includes(url.hostname)) {
    throw new Error("Fooocus must be bound to localhost. Never expose its Gradio port to the internet.");
  }
  return url.toString();
}
export async function scanFiles(root, suffixes = imageExtensions, maxDepth = 4) {
  const all = [];
  async function visit(folder, depth) {
    if (depth > maxDepth) return;
    const entries = await readdir(folder, { withFileTypes: true }).catch(() => []);
    for (const ent of entries) {
      const full = path.join(folder, ent.name);
      if (ent.isDirectory()) await visit(full, depth + 1);
      else if (ent.isFile() && suffixes.has(path.extname(ent.name).toLowerCase())) {
        const info = await stat(full).catch(() => null);
        if (info?.size > 64) all.push({ path: full, size: info.size, modified: info.mtimeMs });
      }
    }
  }
  await visit(root, 0);
  return all.sort((a, b) => b.modified - a.modified);
}
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
export async function fooocusHealth() {
  const url = assertLocalFooocusUrl();
  try {
    const response = await fetch(url, { signal: AbortSignal.timeout(2500) });
    return response.ok;
  } catch { return false; }
}
async function waitForFreshImage(existed, beganAt, timeoutMs = 12 * 60 * 1000) {
  const deadline = Date.now() + timeoutMs;
  let candidate = "";
  let stableSize = 0;
  while (Date.now() < deadline) {
    const items = await scanFiles(OUTPUT_DIR);
    const item = items.find(f => !existed.has(f.path) && f.modified >= beganAt - 2000);
    if (item) {
      if (candidate === item.path && stableSize === item.size && item.size < 18_000_000) return item.path;
      candidate = item.path;
      stableSize = item.size;
    }
    await sleep(1500);
  }
  throw new Error("Fooocus produced no new saved image before the local generation timeout. Review the Fooocus terminal logs.");
}
export async function generateUsingOfficialFooocus(prompt) {
  const url = assertLocalFooocusUrl();
  if (!await fooocusHealth()) throw new Error("Official Fooocus is offline. Run START-FOOOCUS-AMD.bat on this PC first.");
  await mkdir(OUTPUT_DIR, { recursive: true });
  await mkdir(STORE, { recursive: true });
  const existed = new Set((await scanFiles(OUTPUT_DIR)).map(x => x.path));
  let browser;
  try {
    browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--no-first-run", "--no-default-browser-check"] });
    const page = await browser.newPage();
    await page.goto(url, { waitUntil: "domcontentloaded", timeout: 60000 });
    const box = page.locator('#positive_prompt textarea, textarea#positive_prompt, textarea[placeholder="Type prompt here or paste parameters."]').first();
    await box.waitFor({ state: "visible", timeout: 60000 });
    await box.fill(prompt);
    // Apply a restrictive negative prompt where the official UI exposes it.
    const negative = page.locator('#negative_prompt textarea, textarea#negative_prompt').first();
    if (await negative.count() && await negative.isVisible()) {
      await negative.fill("nudity, explicit sexual content, pornography, minors, graphic violence");
    }
    const generate = page.locator("#generate_button button, button#generate_button").first();
    await generate.waitFor({ state: "visible", timeout: 60000 });
    const beganAt = Date.now();
    await generate.click();
    const output = await waitForFreshImage(existed, beganAt);
    const ext = path.extname(output).toLowerCase();
    const dest = path.join(STORE, (await import("node:crypto")).randomBytes(16).toString("hex") + ext);
    await copyFile(output, dest);
    // Only remove the source file generated by our dedicated Fooocus output directory.
    await unlink(output).catch(() => {});
    return { path: dest, ext };
  } catch (e) {
    if (String(e.message || "").includes("Executable doesn't exist")) throw new Error("Google Chrome is required for local Fooocus automation.");
    throw e;
  } finally {
    if (browser) await browser.close().catch(() => {});
  }
}
// Remove residual Fooocus history and intermediate files, honoring app retention.
// Only touches our dedicated output/temp directories, never a user's independent Fooocus install.
export async function purgeFooocusResiduals(cutoff) {
  for (const root of [OUTPUT_DIR, TEMP_DIR]) {
    const entries = await scanFiles(root, removableExtensions, 5);
    for (const item of entries) {
      if (item.modified < cutoff) await unlink(item.path).catch(() => {});
    }
  }
}
